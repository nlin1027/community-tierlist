-- Community tierlist: one row per (user, character, tier) submission.
-- Column names match the queries in api/app.js ("user", character, tier).

create table if not exists public.deadlock (
  id        bigint generated by default as identity primary key,
  "user"    text        not null check ("user" ~ '^[a-zA-Z0-9]{3,20}$'),
  character text        not null,
  tier      char(1)     not null check (tier in ('D', 'C', 'B', 'A', 'S', 'Z')),
  date      timestamptz not null default now()
);

-- /get_character filters by character; /average_list groups by it.
create index if not exists deadlock_character_idx on public.deadlock (character);

-- Lock the table against Supabase's auto-generated REST API (anon/publishable
-- key). No policies = no access. The Express server connects as the postgres
-- role via DATABASE_URL, which bypasses RLS, so the API is unaffected.
alter table public.deadlock enable row level security;
